package com.andrei1058.bedwars.listeners

import com.andrei1058.bedwars.BedWars
import com.andrei1058.bedwars.arena.Arena
import java.lang.reflect.Method
import java.util.HashSet
import org.bukkit.Bukkit
import org.bukkit.Chunk
import org.bukkit.Material
import org.bukkit.World
import org.bukkit.entity.Entity
import org.bukkit.entity.EntityType
import org.bukkit.event.EventHandler
import org.bukkit.event.EventPriority
import org.bukkit.event.Listener
import org.bukkit.event.world.ChunkLoadEvent

/**
 * Safety net: arena maps are void outside the area that was built. If a world of an arena ends up with a vanilla
 * chunk generator anyway (a restore adapter that did not pass the void generator, a stale world folder...), every
 * chunk that has to be generated is emptied again instead of showing vanilla terrain around the map.
 * Chunks that come from the map files are never touched.
 */
open class VoidGuardListener : Listener {
    private val warned: MutableSet<String> = HashSet()
    private var minHeight: Method? = null

    @EventHandler(priority = EventPriority.LOWEST)
    open fun onChunkLoad(e: ChunkLoadEvent) {
        if (!e.isNewChunk()) {
            return
        }
        val world = e.getWorld()
        // generated by a void generator already
        if (world.getGenerator() != null) {
            return
        }
        if (Arena.getArenaByIdentifier(world.getName()) == null) {
            return
        }
        if (warned.add(world.getName())) {
            BedWars.plugin.getLogger().warning("The world of arena '" + world.getName() + "' uses the vanilla chunk generator. " + "Chunks outside the map are emptied to keep it void; check which plugin creates the world without the void generator.")
        }
        clear(e.getChunk())
    }

    private fun clear(chunk: Chunk) {
        val world = chunk.getWorld()
        var min: Int = 0
        try {
            if (minHeight == null) {
                minHeight = World::class.java.getMethod("getMinHeight")
            }
            min = minHeight.invoke(world) as Int
        } catch (ignored: Throwable) {
            // old API: worlds start at 0
        }
        val max: Int = world.getMaxHeight()
        for (x in 0 until 16) {
            for (z in 0 until 16) {
                for (y in max - 1 downTo min) {
                    val b = chunk.getBlock(x, y, z)
                    if (b.getType() != Material.AIR) {
                        b.setType(Material.AIR, false)
                    }
                }
            }
        }
        for (en in chunk.getEntities()) {
            if (en.getType() != EntityType.PLAYER) {
                en.remove()
            }
        }
    }
}
